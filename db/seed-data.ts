// Helper to fill up to 45 episodes with standard editorial continuity
export function generateFull45Episodes(): CsvRow[] {
  const list: CsvRow[] = [...INITIAL_45_EPISODES];
  
  const seriesDistribution: Array<{ prefix: string; playlist: string; count: number }> = [
    { prefix: "B1-B2", playlist: "Intermediate Mastery (B1-B2)", count: 15 },
    { prefix: "MIND", playlist: "Mindset & Psychology", count: 10 },
    { prefix: "CAR", playlist: "Career & Business English", count: 10 },
    { prefix: "LIFE", playlist: "Life & Social English", count: 10 },
  ];

  let currentId = list.length + 1;

  for (const s of seriesDistribution) {
    for (let i = 1; i <= s.count; i++) {
      const code = `${s.prefix}_${i.toString().padStart(2, "0")}`;
      // if not already present
      if (!list.some((item) => item["Code Série"] === code)) {
        list.push({
          "ID Global": currentId.toString(),
          "Code Série": code,
          "Titre de la Vidéo": `${s.playlist} - Essential Module #${i}: Deep Dive and Practical Fluency`,
          "Concept / Playlist": s.playlist,
          "Texte Miniature": `${s.prefix} PART ${i}`,
          "Visuel Miniature": `Modern visual concept for ${s.playlist} episode #${i} with high contrast typography and clean icon set`,
          "Hook (0-15s)": `Mastering English fluency requires structured repetition and deep listening. In this session of ${s.playlist}, we explore key real-world scenarios.`,
          "Mots-Clés (15 tags)": `speak english with flow, english fluency, ${s.prefix.toLowerCase()} english, learn english, intermediate english, english podcast, listening practice, conversation, vocabulary, accent training, daily habit, language flow, audio lessons, fluency tips, master english`,
          "Description Complète": `Welcome to episode ${code} of Speak English With Flow. In this episode from the ${s.playlist} series, we focus on real-world application, active listening exercises, and fluent speech patterns.`
        });
        currentId++;
      }
    }
  }

  // Slice exactly to 45
  return list.slice(0, 45).map((row, idx) => ({
    ...row,
    "ID Global": (idx + 1).toString(),
  }));
}
